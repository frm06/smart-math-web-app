def faktorial(n):

    if n == 0 or n == 1:
        return 1

    return n * faktorial(n - 1)


def hitung_faktorial(n):

    if n is None:
        return "Masukkan bilangan."

    if n < 0:
        return "Bilangan harus 0 atau lebih."

    if n != int(n):
        return "Masukkan bilangan bulat."

    hasil = faktorial(int(n))

    return f"{int(n)}! = {hasil}"


