def periksa_jawaban(
    index,
    skor,
    sudah_diperiksa,
    jawaban
):

    if sudah_diperiksa:

        return (
            skor,
            True,
            "Jawaban sudah diperiksa. "
            "Silakan lanjut ke soal berikutnya.",

            gr.update(
                interactive=False
            ),

            gr.update(
                interactive=False
            ),

            gr.update(
                visible=False
            )
        )


    if jawaban is None:

        return (
            skor,
            False,
            "Silakan pilih jawaban terlebih dahulu.",

            gr.update(
                interactive=True
            ),

            gr.update(
                interactive=False
            ),

            gr.update(
                visible=False
            )
        )


    soal = quiz_questions[index]


    if jawaban == soal["answer"]:

        skor_baru = skor + 20

        hasil = (
            "✅ Benar!\n"
            "Kamu mendapatkan 20 poin."
        )

    else:

        skor_baru = skor

        hasil = (
            "❌ Jawaban belum tepat.\n"
            f"Jawaban yang benar adalah "
            f"{soal['answer']}."
        )


    soal_terakhir = (
        index == len(quiz_questions) - 1
    )


    if soal_terakhir:

        hasil += (
            "\n\n🎉 Quiz selesai!"
            f"\nTotal skor kamu: "
            f"{skor_baru} dari 100."
        )

        return (
            skor_baru,
            True,
            hasil,

            gr.update(
                interactive=False
            ),

            gr.update(
                interactive=False
            ),

            gr.update(
                visible=True
            )
        )

    else:

        return (
            skor_baru,
            True,
            hasil,

            gr.update(
                interactive=False
            ),

            gr.update(
                interactive=True
            ),

            gr.update(
                visible=False
            )
        )


