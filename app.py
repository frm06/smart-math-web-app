# 5. MENGHITUNG LUAS
# =========================================================

def hitung_luas(bangun, angka1, angka2, angka3):

    if bangun is None:
        return "Silakan pilih bangun terlebih dahulu."

    # -------------------------
    # PERSEGI
    # -------------------------

    if bangun == "Persegi":

        if angka1 is None:
            return "Masukkan panjang sisi."

        hasil = luas_persegi(angka1)

        return f"Luas persegi = {hasil}"


    # -------------------------
    # PERSEGI PANJANG
    # -------------------------

    elif bangun == "Persegi Panjang":

        if angka1 is None or angka2 is None:
            return "Masukkan panjang dan lebar."

        hasil = luas_persegi_panjang(
            angka1,
            angka2
        )

        return f"Luas persegi panjang = {hasil}"


    # -------------------------
    # SEGITIGA
    # -------------------------

    elif bangun == "Segitiga":

        if angka1 is None or angka2 is None:
            return "Masukkan alas dan tinggi."

        hasil = luas_segitiga(
            angka1,
            angka2
        )

        return f"Luas segitiga = {hasil}"


