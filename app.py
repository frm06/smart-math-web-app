# 9. ANALISIS DATA
# =========================================================

def analisis_data(teks):

    data = ubah_data(teks)

    if len(data) == 0:
        return "Data tidak valid atau masih kosong."

    data_urut = sorted(data)

    nilai_maksimum = max(data)
    nilai_minimum = min(data)

    jumlah_data = len(data)

    rata_rata = sum(data) / jumlah_data

    hasil = f"""
Data asli:
{data}

Data setelah diurutkan:
{data_urut}

Nilai maksimum:
{nilai_maksimum}

Nilai minimum:
{nilai_minimum}

Jumlah data:
{jumlah_data}

Rata-rata:
{rata_rata:.2f}
"""

    return hasil


