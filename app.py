# =========================================================

def cari_data(teks, target):

    data = ubah_data(teks)

    if len(data) == 0:
        return "Data tidak valid atau masih kosong."

    if target is None:
        return "Masukkan nilai yang ingin dicari."

    posisi = []

    for nomor, nilai in enumerate(data, start=1):

        if nilai == target:
            posisi.append(nomor)

    if len(posisi) == 0:

        return (
            f"Nilai {target} tidak ditemukan dalam data."
        )

    if len(posisi) == 1:

        return (
            f"Nilai {target} ditemukan.\n"
            f"Nilai tersebut terdapat pada "
            f"data ke-{posisi[0]}."
        )

    else:

        daftar_posisi = ", ".join(
            [f"data ke-{p}" for p in posisi]
        )

        return (
            f"Nilai {target} ditemukan sebanyak "
            f"{len(posisi)} kali.\n"
            f"Nilai tersebut terdapat pada "
            f"{daftar_posisi}."
        )


